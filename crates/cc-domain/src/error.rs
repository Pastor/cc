//! Нарушения инвариантов предметной области.

/// Отказ построить значение предметной области.
///
/// Тип, который можно собрать в недопустимом состоянии, спроектирован неверно,
/// поэтому каждый конструктор отвечает одним из этих вариантов.
#[derive(Debug, thiserror::Error, PartialEq, Eq)]
#[non_exhaustive]
pub enum Error {
    /// Имя пользователя не является адресом электронной почты.
    #[error("имя пользователя не является адресом электронной почты")]
    Username,
    /// Хеш содержимого не является 64 символами шестнадцатеричной записи.
    #[error("хеш содержимого не является 64 символами шестнадцатеричной записи")]
    ContentHash,
    /// Идентификатор не является допустимым UUID.
    #[error("идентификатор не является допустимым UUID")]
    Identifier,
    /// Израсходованный объём превышает предел квоты.
    #[error("израсходовано больше, чем допускает квота")]
    QuotaOverrun,
    /// Название права не распознано.
    #[error("право {name} не распознано")]
    UnknownRight {
        /// Название, встреченное во входных данных.
        name: String,
    },
    /// Права получателя шире прав выдающего.
    #[error("права получателя шире прав выдающего")]
    RightsEscalation,
}

/// Результат построения значения предметной области.
pub type Result<T> = core::result::Result<T, Error>;
