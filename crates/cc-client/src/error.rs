//! Отказы клиентского ядра.

/// Отказ клиентской операции.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum Error {
    /// Отказ криптографического примитива.
    #[error(transparent)]
    Crypto(#[from] cc_crypto::Error),
    /// Выведение ключа из пароля не удалось.
    #[error("выведение ключа из пароля не удалось")]
    Kdf,
    /// Запись ключа восстановления не разобрана.
    #[error("запись ключа восстановления не разобрана: проверьте символы")]
    Recovery,
    /// Отпечаток открытого ключа получателя не совпал с ожидаемым.
    #[error("отпечаток открытого ключа получателя не совпал с ожидаемым")]
    Fingerprint,
}

/// Результат клиентской операции.
pub type Result<T> = core::result::Result<T, Error>;
