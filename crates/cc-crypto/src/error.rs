//! Отказы криптографического слоя.

/// Отказ криптографической операции.
///
/// Варианты намеренно не содержат ни ключевого материала, ни открытого текста:
/// сообщение об ошибке попадает в журнал и к пользователю.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum Error {
    /// Соль короче допустимого предела.
    #[error("соль короче {expected} байт")]
    SaltTooShort {
        /// Наименьшая допустимая длина соли.
        expected: usize,
    },
    /// Параметры выведения ключа недопустимы.
    #[error("параметры выведения ключа недопустимы")]
    KdfParameters,
    /// Выведение ключа из пароля не удалось.
    #[error("выведение ключа из пароля не удалось")]
    KeyDerivation,
    /// Расшифровка не удалась: ключ не тот либо данные искажены.
    #[error("расшифровка не удалась: неверный ключ либо искажённые данные")]
    Decryption,
    /// Заголовок зашифрованного файла короче обязательной части.
    #[error("заголовок короче {expected} байт")]
    HeaderTooShort {
        /// Наименьшая допустимая длина заголовка.
        expected: usize,
    },
    /// Версия формата шифрования не поддерживается.
    #[error("версия формата шифрования {found} не поддерживается")]
    UnsupportedFormat {
        /// Версия, встреченная в заголовке.
        found: u8,
    },
    /// Размер блока вне допустимого диапазона.
    #[error("размер блока вне диапазона от {min} до {max} байт")]
    BlockSize {
        /// Наименьший допустимый размер блока.
        min: u32,
        /// Наибольший допустимый размер блока.
        max: u32,
    },
    /// Блок короче обязательной служебной части.
    #[error("блок короче {expected} байт")]
    BlockTooShort {
        /// Наименьшая допустимая длина блока.
        expected: usize,
    },
    /// Номер блока выходит за пределы файла.
    #[error("номер блока {index} выходит за пределы файла")]
    BlockOutOfRange {
        /// Запрошенный номер блока.
        index: u64,
    },
    /// Источник случайности недоступен.
    #[error("источник случайности недоступен")]
    Randomness,
}

/// Результат криптографической операции.
pub type Result<T> = core::result::Result<T, Error>;
