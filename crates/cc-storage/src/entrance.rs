//! Внешний вход.
//!
//! Провайдеры проверяют присланное каждый по своему протоколу, но отвечают
//! одним и тем же: проверенной внешней личностью либо отказом. Общего слоя
//! `OAuth2` у них нет — у Telegram его нет вовсе (`TODO.md`, раздел 4.3).

use crate::error::Result;
use cc_domain::ExternalIdentity;
use core::future::Future;
use time::OffsetDateTime;

/// Вход через внешнего провайдера.
///
/// Учётной записи трейт не создаёт и создать не может: без пароля не из чего
/// вывести мастер-ключ. Его дело — установить, кто пришёл.
pub trait Entrance {
    /// То, что провайдер присылает в подтверждение личности.
    type Artifacts;

    /// Проверяет присланное и возвращает личность.
    ///
    /// # Errors
    ///
    /// Отказ проверки: подпись не сошлась, данные устарели, ответ повторён
    /// либо провайдер ответил отказом.
    fn identity(
        &self,
        artifacts: Self::Artifacts,
        now: OffsetDateTime,
    ) -> impl Future<Output = Result<ExternalIdentity>> + Send;
}
