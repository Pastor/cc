//! Отказы хранилища.

/// Отказ операции хранилища.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum Error {
    /// Логин уже занят.
    #[error("логин уже занят")]
    LoginTaken,
    /// Подпись данных провайдера не сошлась.
    #[error("подпись данных провайдера не сошлась")]
    Signature,
    /// Данные провайдера старше окна свежести.
    #[error("данные провайдера старше окна свежести")]
    Expired,
    /// Предъявленная редакция разошлась с текущей.
    #[error("предъявленная редакция разошлась с текущей")]
    Stale,
    /// Данные провайдера уже предъявлялись.
    #[error("данные провайдера уже предъявлялись")]
    Replay,
    /// Значение не соответствует ожидаемому формату.
    #[error("значение не соответствует ожидаемому формату")]
    Malformed,
    /// Внешняя личность уже привязана к другой учётной записи.
    #[error("внешняя личность уже привязана к другой учётной записи")]
    IdentityTaken,
    /// Запись отсутствует.
    #[error("запись отсутствует")]
    Missing,
    /// Размер или хеш принятого шифротекста не совпал с заявленным.
    #[error("размер или хеш шифротекста не совпал с заявленным")]
    ContentMismatch,
    /// Построенный путь выходит за пределы корня хранилища.
    #[error("построенный путь выходит за пределы корня хранилища")]
    PathEscape,
    /// Отказ файловой системы.
    #[error("отказ файловой системы")]
    Io(#[from] std::io::Error),
    /// Нарушение инварианта предметной области.
    #[error(transparent)]
    Domain(#[from] cc_domain::Error),
    /// Отказ криптографического примитива.
    #[error(transparent)]
    Crypto(#[from] cc_crypto::Error),
}

/// Результат операции хранилища.
pub type Result<T> = core::result::Result<T, Error>;
